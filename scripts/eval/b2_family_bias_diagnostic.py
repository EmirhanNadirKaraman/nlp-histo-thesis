#!/usr/bin/env python3
"""
b2_family_bias_diagnostic.py — per-voter cosine-similarity distribution vs silver.

Diagnostic for the EXP B.2 family-bias question: silver was generated by
``claude-opus-4-7``, and Haiku/Sonnet (Anthropic-family) outperformed
gpt-4.1-mini on strict_f1 by 2.8-7pp. Is the gap real model quality, or is
the OpenAI matcher embedding-of-claim-text systematically favouring
Anthropic-family phrasing?

Replay-only — reads ``eval/data/map_primer/voter_cache.json`` + the OpenAI
matcher embedding cache (`embedding_cache_openai.sqlite`). Assumes the
cache is warm (`scripts/eval/run_summarization_experiments.py --phase
baselines --run` populates it). No API calls when warm; if a miss occurs,
OPENAI_API_KEY is required.

Two diagnostic statistics per voter:

  (a) ``mean_matched_sim`` — average cosine over matched (≥ sim_threshold)
      pairs. If Anthropic voters' accepted matches systematically score
      higher cosine than non-Anthropic voters with similar strict_f1, the
      matcher may be family-correlated rather than measuring claim
      equivalence cleanly.

  (b) ``mean_best_per_silver_sim`` — for every silver finding, the maximum
      cosine to any of that voter's findings (threshold-free).  Average
      across silver findings. Measures how close the voter's full output
      "gets to" each silver claim.

If Anthropic dominates BOTH stats and OpenAI's gpt-4.1-mini lags by more
than its strict_f1 deficit suggests → family bias is the parsimonious
explanation. If they're tied on (b) but not (a) → the bias (if any) lives
in the threshold band and is small.

Usage::

    python scripts/eval/b2_family_bias_diagnostic.py                          # split=dev
    python scripts/eval/b2_family_bias_diagnostic.py --split test
    python scripts/eval/b2_family_bias_diagnostic.py --split all
"""
from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import os
import statistics
import sys
from datetime import datetime, timezone
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
# Frozen repository cache — these drivers must hit the SAME sqlite file the thesis
# used, or they would miss and issue PAID embedding calls.
_FROZEN_OPENAI_CACHE = _REPO_ROOT / "eval" / "data" / "embedding_cache_openai.sqlite"

if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from dotenv import load_dotenv
load_dotenv(str(_REPO_ROOT / ".env"))

from nlp_histo.evaluation.jsonl_utils import read_jsonl
from nlp_histo.evaluation.schemas import SilverCaseResult
from nlp_histo.evaluation.matching.matcher import (
    EMBEDDING_MODEL, compute_sim_matrix, match_from_matrix,
    make_embedding_cache,
)
from nlp_histo.evaluation.matching.embedders import OpenAIEmbedder
from nlp_histo.evaluation.split import assign_split


# Voter spec: position in voter_cache list → (model, family)
# Matches `pipeline.stages.knowledge_extraction.batch.voter_configs.make_l*_voters`
# at the time of this script. If the production profile changes, update here.
VOTER_SPECS = [
    ("l1", 0, "gemini-2.5-flash-lite",        "Gemini"),
    ("l1", 1, "gpt-4o-mini",                  "OpenAI"),
    ("l1", 2, "gpt-4.1-nano",                 "OpenAI"),
    ("l2", 0, "gemini-2.5-flash",             "Gemini"),
    ("l2", 1, "gpt-4.1-mini",                 "OpenAI"),
    ("l2", 2, "claude-haiku-4-5-20251001",    "Anthropic"),
    ("l3", 0, "claude-sonnet-4-6",            "Anthropic"),
]


def _load_orch_helpers():
    """Load `_b2_build_voter_outputs` from the orchestrator (scripts/ isn't a package)."""
    spec = importlib.util.spec_from_file_location(
        "rse_orch",
        _REPO_ROOT / "scripts" / "eval" / "run_summarization_experiments.py",
    )
    mod = importlib.util.module_from_spec(spec)
    sys.modules["rse_orch"] = mod
    spec.loader.exec_module(mod)
    return mod


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--split", default="dev", choices=["dev", "test", "all"])
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--dev-fraction", type=float, default=0.8)
    p.add_argument("--sim-threshold", type=float, default=0.55)
    p.add_argument(
        "--output-dir", default=str(_REPO_ROOT / "eval" / "reports"),
        help="Where to write the diagnostic CSV.",
    )
    args = p.parse_args(argv)

    cache_path = _REPO_ROOT / "eval" / "data" / "map_primer" / "voter_cache.json"
    silver_path = _REPO_ROOT / "eval" / "data" / "silver_findings_related15.jsonl"
    if not cache_path.exists():
        raise SystemExit(f"voter cache not found: {cache_path}")
    if not silver_path.exists():
        raise SystemExit(f"silver labels not found: {silver_path}")

    voter_cache = json.loads(cache_path.read_text(encoding="utf-8"))
    silver_by_case = {
        r.case_id: r for r in read_jsonl(silver_path, SilverCaseResult)
    }

    api_key = os.environ.get("OPENAI_API_KEY", "")
    if not api_key:
        raise SystemExit(
            "OPENAI_API_KEY not set; matcher embedder is OpenAI "
            "text-embedding-3-small. Set the key (cache covers most texts; "
            "any miss costs <$0.001) and re-run."
        )
    embedder = OpenAIEmbedder(api_key)
    embed_cache = make_embedding_cache(_FROZEN_OPENAI_CACHE, EMBEDDING_MODEL)

    orch = _load_orch_helpers()

    def in_split(case_id: str) -> bool:
        if args.split == "all":
            return True
        return assign_split(case_id, args.dev_fraction, args.seed) == args.split

    rows: list[dict] = []
    print(
        f"\nFamily-bias diagnostic — split={args.split}  "
        f"sim_threshold={args.sim_threshold}\n"
    )
    print(
        f"{'voter':<35} {'family':<10} {'n_match':>8} "
        f"{'mean_match':>11} {'std_match':>10} "
        f"{'mean_best':>10} {'p50_best':>9} {'p95_best':>9}"
    )
    print("-" * 116)

    for level, idx, model, family in VOTER_SPECS:
        outputs = orch._b2_build_voter_outputs(
            voter_cache, level=level, voter_index=idx, case_filter=in_split,
        )
        matched_sims: list[float] = []
        best_per_silver: list[float] = []
        for co in outputs:
            silver = silver_by_case.get(co.case_id)
            if silver is None or not silver.findings:
                continue
            sim, _, _ = compute_sim_matrix(silver, co, embedder, embed_cache)
            if not sim:
                # voter produced no findings for this case → every silver
                # finding's best-shot is 0.
                best_per_silver.extend([0.0] * len(silver.findings))
                continue
            for row in sim:
                best_per_silver.append(max(row) if row else 0.0)
            result = match_from_matrix(silver, co, sim, args.sim_threshold)
            for pair in result.matched:
                matched_sims.append(pair.similarity)

        n_m = len(matched_sims)
        if matched_sims:
            mean_m = statistics.mean(matched_sims)
            std_m  = statistics.stdev(matched_sims) if n_m > 1 else 0.0
        else:
            mean_m = std_m = 0.0

        if best_per_silver:
            sorted_b = sorted(best_per_silver)
            mean_b = statistics.mean(best_per_silver)
            p50_b  = sorted_b[len(sorted_b) // 2]
            p95_b  = sorted_b[min(len(sorted_b) - 1, int(0.95 * len(sorted_b)))]
        else:
            mean_b = p50_b = p95_b = 0.0

        print(
            f"{model:<35} {family:<10} {n_m:>8} "
            f"{mean_m:>11.4f} {std_m:>10.4f} "
            f"{mean_b:>10.4f} {p50_b:>9.4f} {p95_b:>9.4f}"
        )
        rows.append({
            "split":              args.split,
            "voter_level":        level,
            "voter_index":        idx,
            "model":              model,
            "family":             family,
            "n_silver_findings":  len(best_per_silver),
            "n_matched":          n_m,
            "mean_matched_sim":   round(mean_m, 4),
            "std_matched_sim":    round(std_m, 4),
            "mean_best_per_silver_sim": round(mean_b, 4),
            "p50_best_per_silver_sim":  round(p50_b, 4),
            "p95_best_per_silver_sim":  round(p95_b, 4),
            "sim_threshold":      args.sim_threshold,
            "seed":               args.seed,
            "dev_fraction":       args.dev_fraction,
        })

    # Family-level aggregate
    families: dict[str, list[dict]] = {}
    for r in rows:
        families.setdefault(r["family"], []).append(r)

    print("\nFamily aggregates (mean across the family's voters):")
    print(f"{'family':<12} {'n_voters':>9} {'mean_matched_sim':>18} {'mean_best_per_silver':>22}")
    print("-" * 65)
    for fam in sorted(families):
        vs = families[fam]
        avg_m = statistics.mean(r["mean_matched_sim"] for r in vs)
        avg_b = statistics.mean(r["mean_best_per_silver_sim"] for r in vs)
        print(f"{fam:<12} {len(vs):>9} {avg_m:>18.4f} {avg_b:>22.4f}")

    # CSV
    ts = datetime.now(tz=timezone.utc).strftime("%Y%m%dT%H%M%S")
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = out_dir / f"exp_b2_family_bias_diagnostic_{ts}.csv"
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        for r in rows:
            writer.writerow(r)
    print(f"\nWrote: {csv_path}")

    # Interpretation hint
    print("\nInterpretation:")
    print("  mean_matched_sim diverging across families → bias in the matched-pair zone.")
    print("  mean_best_per_silver_sim diverging across families → bias is threshold-free")
    print("  (the embedder + silver text style genuinely favour one family).")
    print(
        "  If Anthropic family stats > OpenAI family stats by ≳ "
        f"{args.sim_threshold * 0.10:.3f} on either metric, take it as evidence."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
